/**
 * Regenerate docs/academy-reading-material.txt from the lessons.
 *
 *   node --experimental-strip-types scripts/reading-material.mjs
 *
 * The handout has always claimed at the top of its own first page that it is
 * generated and must not be hand-edited. It was not - it was produced once by
 * hand, which is how it came to sit three lessons out of date while still
 * telling its reader it was current. This script makes the claim true.
 *
 * `lessons.ts` and `days.ts` are imported directly: Node 22 strips the type
 * annotations, and both modules are plain data with type-only imports, so there
 * is nothing to compile and no parser to keep in step with the content.
 */

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

import { LESSONS } from "../src/content/onboarding/lessons.ts";
import { DAYS } from "../src/content/onboarding/days.ts";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "docs", "academy-reading-material.txt");

/** Rule widths, kept as constants so the two never drift apart. */
const HEAVY = "=".repeat(74);
const LIGHT = "-".repeat(74);

/** Lessons in day order, numbered `day.index` the way the contents list them. */
function numbered() {
  return DAYS.flatMap((day) =>
    LESSONS.filter((lesson) => lesson.dayId === day.id).map(
      (lesson, index) => ({
        day,
        lesson,
        number: `${day.id}.${index + 1}`,
      }),
    ),
  );
}

const entries = numbered();
const out = [];

out.push("ATLYS ACADEMY - READING MATERIAL");
out.push("Three days, every lesson, verbatim from the app.");
out.push("");
out.push("GENERATED from src/content/onboarding/lessons.ts - do not edit this file.");
out.push("Edit the lessons, then regenerate. A stale copy of teaching content is");
out.push("how a wrong answer reaches a paying guest.");
out.push("");
out.push("CONTENTS");

for (const day of DAYS) {
  out.push(`  Day ${day.id} - ${day.title}`);
  for (const entry of entries.filter((item) => item.day.id === day.id)) {
    out.push(`    ${entry.number}  ${entry.lesson.title}`);
  }
}

for (const day of DAYS) {
  const forDay = entries.filter((entry) => entry.day.id === day.id);

  out.push("");
  out.push(HEAVY);
  out.push(`DAY ${day.id} - ${day.title.toUpperCase()}`);
  out.push(`Objective: ${day.objective}`);
  out.push(`${forDay.length} lessons`);
  out.push(HEAVY);

  for (const { number, lesson } of forDay) {
    out.push("");
    out.push(`${number}  ${lesson.title}`);
    out.push(LIGHT);

    // A lesson with no body is one still pending from its owner. Print who it
    // is waiting on rather than a blank heading, so the gap is legible on paper
    // as well as in the app.
    if (!lesson.body) {
      out.push(
        `[Not written yet${lesson.pendingWith ? ` - pending with ${lesson.pendingWith}` : ""}.]`,
      );
      continue;
    }

    // Blank line between paragraphs: this is read on paper, and a lesson that
    // runs eight paragraphs together is a wall nobody finishes.
    lesson.body.forEach((paragraph, index) => {
      if (index > 0) out.push("");
      out.push(paragraph);
    });

    if (lesson.example) {
      out.push("");
      out.push(`IN PRACTICE: ${lesson.example}`);
    }
    if (lesson.commonMistake) {
      out.push("");
      out.push(`WHAT NEW JOINERS GET WRONG: ${lesson.commonMistake}`);
    }
  }
}

out.push("");
writeFileSync(OUT, out.join("\n"), "utf8");
console.log(
  `Wrote ${OUT}\n${entries.length} lessons across ${DAYS.length} days.`,
);
